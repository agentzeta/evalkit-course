"""Leakage diagnostics for synthetic and generated benchmarks.

A benchmark built by generating items *conditional on the label* contains a
trapdoor: some function of the item recovers the label without doing the task.
This module provides the battery that finds it before the benchmark ships.

Three tests, in increasing order of what they cost you to run:

  1. `template_multiplicity` -- how many distinct items are there really, and
     what is the effective sample size once you account for repeats? Free.
  2. `degenerate_baselines`  -- can a solver that does none of the task beat
     the trivial baseline? Cheap.
  3. `ceiling_violation`     -- does any of them exceed a ceiling you claimed
     was irreducible? This is the sound detector: a violation is proof.

The asymmetry worth internalising: a violation **proves** leakage, but no
violation proves nothing. The battery is sound, not complete.

Nothing here is specific to text. Any benchmark whose items were produced from
the labels -- generated by a model, templated, or assembled from class-specific
pools -- is a candidate.
"""

from __future__ import annotations

import math
import random
import re
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from typing import Callable, Hashable, Sequence


# --------------------------------------------------------------------------
# 1. How much of this benchmark is actually distinct?
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class Multiplicity:
    n_rows: int
    n_distinct: int
    max_reuse: int
    mean_cluster: float
    constant_label_groups: int
    mixed_label_groups: int

    @property
    def all_groups_constant(self) -> bool:
        return self.mixed_label_groups == 0

    @property
    def effective_n(self) -> int:
        """Independent units available for label inference.

        When every group carries a single label the intra-cluster correlation
        is 1, each group contributes exactly one independent observation, and
        the effective sample size is the number of GROUPS -- regardless of how
        many rows each contains. 200 rows drawn from 18 templates is an n=18
        study wearing an n=200 costume.

        With mixed-label groups the correlation is below 1 and the effective n
        lies between the group count and the row count; `design_effect_n`
        gives the standard approximation.
        """
        return self.n_distinct if self.all_groups_constant else self.n_rows

    def design_effect_n(self, icc: float) -> float:
        """n / (1 + (m_A - 1) * icc), the usual clustered-design correction.

        m_A is the size-weighted mean cluster size, which is the right average
        here because large clusters dominate the variance inflation. Pass the
        intra-cluster correlation you have estimated; icc=1 recovers the group
        count.
        """
        if not 0.0 <= icc <= 1.0:
            raise ValueError("icc must be in [0, 1]")
        m_a = self.mean_cluster
        return self.n_rows / (1.0 + (m_a - 1.0) * icc)

    def summary(self) -> str:
        warn = ""
        if self.n_distinct < self.n_rows * 0.5:
            warn = "   <-- fewer than half the rows are distinct"
        return (
            f"rows {self.n_rows}, distinct items {self.n_distinct}, "
            f"max reuse {self.max_reuse}{warn}\n"
            f"groups with a constant label: {self.constant_label_groups} of "
            f"{self.n_distinct}\n"
            f"effective n for label inference: {self.effective_n}"
        )


def template_multiplicity(
    items: Sequence[Hashable], labels: Sequence[int]
) -> Multiplicity:
    """Count distinct items and check whether labels are constant within them.

    Pass the raw items (text, prompt, whatever the unit is). Repeats are the
    clusters; this reports how badly the row count overstates the evidence.
    """
    if len(items) != len(labels):
        raise ValueError(f"{len(items)} items but {len(labels)} labels")
    if not items:
        return Multiplicity(0, 0, 0, 0.0, 0, 0)

    by_item: dict[Hashable, list[int]] = defaultdict(list)
    for it, y in zip(items, labels):
        by_item[it].append(y)

    sizes = [len(v) for v in by_item.values()]
    # Size-weighted mean cluster size: sum(m^2) / sum(m).
    m_a = sum(s * s for s in sizes) / sum(sizes)
    const = sum(1 for v in by_item.values() if len(set(v)) == 1)

    return Multiplicity(
        n_rows=len(items),
        n_distinct=len(by_item),
        max_reuse=max(sizes),
        mean_cluster=m_a,
        constant_label_groups=const,
        mixed_label_groups=len(by_item) - const,
    )


# --------------------------------------------------------------------------
# 2. Solvers that do none of the task
# --------------------------------------------------------------------------


def _f1(pred: Sequence[int], labels: Sequence[int]) -> float:
    tp = sum(1 for p, y in zip(pred, labels) if p == 1 and y == 1)
    fp = sum(1 for p, y in zip(pred, labels) if p == 1 and y == 0)
    fn = sum(1 for p, y in zip(pred, labels) if p == 0 and y == 1)
    pr = tp / (tp + fp) if tp + fp else 0.0
    rc = tp / (tp + fn) if tp + fn else 0.0
    return 2 * pr * rc / (pr + rc) if pr + rc else 0.0


@dataclass(frozen=True)
class Baseline:
    name: str
    f1: float
    describes: str

    def __str__(self) -> str:
        return f"{self.name:<28} F1 {self.f1:.3f}   {self.describes}"


def _tokens(s: str) -> set[str]:
    return set(re.findall(r"[a-z']{3,}", s.lower()))


def _item_identity_oof(
    texts: Sequence[str], labels: Sequence[int], k: int = 5, seed: int = 0
) -> float:
    """Predict a held-out row's label from other rows carrying the SAME item.

    This is the probe for row-wise split leakage. It does no task work at all:
    it only asks whether the identical item appeared in training, and if so
    copies its majority label. Unseen items fall back to the training prior.
    """
    n = len(texts)
    if n < k:
        return 0.0
    pred = [0] * n
    for tr, te in row_folds(n, k, seed):
        seen: dict[str, list[int]] = defaultdict(list)
        for i in tr:
            seen[texts[i]].append(labels[i])
        n_pos = sum(labels[i] for i in tr)
        prior = 1 if n_pos * 2 >= len(tr) else 0
        for i in te:
            v = seen.get(texts[i])
            pred[i] = (1 if sum(v) * 2 >= len(v) else 0) if v else prior
    return _f1(pred, labels)


def degenerate_baselines(
    texts: Sequence[str],
    labels: Sequence[int],
    extra: dict[str, Callable[[Sequence[str], Sequence[int]], float]] | None = None,
) -> list[Baseline]:
    """Run solvers that cannot possibly be doing the task, and score them.

    Each of these is tuned IN SAMPLE on purpose. The question is not how well
    they generalise -- it is whether the benchmark admits a shortcut at all.
    An in-sample shortcut that reaches a ceiling you called irreducible is a
    construction defect, and reporting its out-of-sample score would hide it.

    The battery:
      flag-everything   the trivial reference every real result must beat
      item identity     memorise which distinct items carry which label
      text length       a property of the generator's verbosity, not the task
      best single token the most label-correlated word, chosen with hindsight
    """
    if len(texts) != len(labels):
        raise ValueError(f"{len(texts)} texts but {len(labels)} labels")
    out: list[Baseline] = []
    if not texts:
        return out

    out.append(
        Baseline("flag-everything", _f1([1] * len(labels), labels),
                 "the trivial reference")
    )

    # Item identity, scored OUT OF FOLD under row-wise splitting.
    #
    # The in-sample version of this baseline is worthless and actively
    # misleading: when every item is unique, memorising each item's label is
    # trivially perfect, so it returns 1.000 on a benchmark with no leakage
    # whatsoever. (This package shipped that false positive; a clean-benchmark
    # negative control caught it.)
    #
    # The out-of-fold version measures the thing that actually matters -- how
    # much a row-wise split leaks. An item seen in training votes its majority
    # label; an unseen item falls back to the training prior. On a benchmark of
    # unique items nothing is ever seen twice, the baseline collapses to the
    # majority class, and the diagnostic correctly stays quiet.
    out.append(
        Baseline(
            "item identity (out-of-fold)",
            _item_identity_oof(texts, labels),
            "memorises repeated items across a row-wise split",
        )
    )

    # Length, thresholded with hindsight.
    lens = [len(t) for t in texts]
    best_len = max(
        (_f1([1 if l >= thr else 0 for l in lens], labels)
         for thr in sorted(set(lens))),
        default=0.0,
    )
    out.append(
        Baseline("text length", best_len,
                 "generator verbosity, unrelated to the task")
    )

    # Single most label-correlated token.
    toks = [_tokens(t) for t in texts]
    vocab = set().union(*toks) if toks else set()
    best_tok = ("", 0.0)
    for w in vocab:
        f = _f1([1 if w in tk else 0 for tk in toks], labels)
        if f > best_tok[1]:
            best_tok = (w, f)
    out.append(
        Baseline("best single token", best_tok[1],
                 f"the word {best_tok[0]!r}, chosen with hindsight")
    )

    for name, fn in (extra or {}).items():
        out.append(Baseline(name, fn(texts, labels), "custom"))

    return sorted(out, key=lambda b: -b.f1)


# --------------------------------------------------------------------------
# 3. The sound detector
# --------------------------------------------------------------------------


@dataclass
class LeakageReport:
    multiplicity: Multiplicity
    baselines: list[Baseline]
    claimed_ceiling: float | None = None
    violations: list[Baseline] = field(default_factory=list)

    @property
    def leaks(self) -> bool:
        return bool(self.violations)

    def summary(self) -> str:
        lines = ["MULTIPLICITY", "  " + self.multiplicity.summary().replace("\n", "\n  "),
                 "", "DEGENERATE BASELINES"]
        trivial = next((b.f1 for b in self.baselines if b.name == "flag-everything"), 0.0)
        for b in self.baselines:
            mark = ""
            if self.claimed_ceiling is not None and b.f1 > self.claimed_ceiling:
                mark = "  *** EXCEEDS CLAIMED CEILING ***"
            elif b.f1 > trivial and b.name != "flag-everything":
                mark = "  (beats trivial)"
            lines.append(f"  {b}{mark}")
        lines.append("")
        if self.claimed_ceiling is None:
            lines.append("VERDICT  no ceiling supplied; ran diagnostics only")
        elif self.leaks:
            worst = max(self.violations, key=lambda b: b.f1)
            lines.append(
                f"VERDICT  LEAKAGE PROVEN. '{worst.name}' reaches "
                f"{worst.f1:.3f} against a claimed ceiling of "
                f"{self.claimed_ceiling:.3f} (+{worst.f1 - self.claimed_ceiling:.3f}). "
                f"A solver that does none of the task cannot legitimately "
                f"exceed the ceiling; the construction leaks."
            )
        else:
            lines.append(
                "VERDICT  no violation found. This does NOT establish that the "
                "benchmark is clean -- the battery is sound, not complete."
            )
        return "\n".join(lines)


def ceiling_violation(
    texts: Sequence[str],
    labels: Sequence[int],
    claimed_ceiling: float | None = None,
    extra: dict[str, Callable[[Sequence[str], Sequence[int]], float]] | None = None,
) -> LeakageReport:
    """The full battery, with the violation test applied if a ceiling is given.

    `claimed_ceiling` is whatever irreducible bound the benchmark's authors
    assert -- a Bayes rate, a label-noise limit, an inter-annotator agreement
    figure, or the score of a reference solver said to have full information.

    The logic is one line: a solver that provably does none of the task cannot
    legitimately beat a bound on solvers that do. If it does, the bound is
    wrong or the items encode the labels. Both are construction defects.
    """
    mult = template_multiplicity(list(texts), labels)
    bases = degenerate_baselines(texts, labels, extra)
    report = LeakageReport(mult, bases, claimed_ceiling)
    if claimed_ceiling is not None:
        report.violations = [b for b in bases if b.f1 > claimed_ceiling]
    return report


# --------------------------------------------------------------------------
# 4. Grouped splitting, and what it costs you to be honest
# --------------------------------------------------------------------------


def group_folds(
    groups: Sequence[Hashable], k: int = 5, seed: int = 0
) -> list[tuple[list[int], list[int]]]:
    """k-fold splits that keep every row of a group on one side.

    Row-wise splitting on a benchmark with repeated items puts the same item
    in train and test, which measures memorisation. Group by whatever unit was
    actually sampled: the template, the prompt that generated the row, the
    conversation, the document, the customer.
    """
    if k < 2:
        raise ValueError("k must be at least 2")
    uniq = sorted(set(groups), key=lambda g: str(g))
    if len(uniq) < k:
        raise ValueError(
            f"only {len(uniq)} groups for {k} folds -- the benchmark does not "
            f"contain enough independent units to cross-validate this way"
        )
    rng = random.Random(seed)
    rng.shuffle(uniq)
    assign = {g: i % k for i, g in enumerate(uniq)}
    return [
        (
            [j for j, g in enumerate(groups) if assign[g] != i],
            [j for j, g in enumerate(groups) if assign[g] == i],
        )
        for i in range(k)
    ]


def row_folds(n: int, k: int = 5, seed: int = 0) -> list[tuple[list[int], list[int]]]:
    """Ordinary row-wise k-fold, provided for the comparison in `grouping_gap`."""
    idx = list(range(n))
    random.Random(seed).shuffle(idx)
    return [
        ([j for j in idx if j % k != i], [j for j in idx if j % k == i])
        for i in range(k)
    ]


@dataclass(frozen=True)
class GroupingGap:
    row_wise_f1: float
    grouped_f1: float
    grouped_folds: list[float]
    overlap_share: float

    @property
    def gap(self) -> float:
        return self.row_wise_f1 - self.grouped_f1

    def summary(self) -> str:
        spread = (
            f"{min(self.grouped_folds):.3f}-{max(self.grouped_folds):.3f}"
            if self.grouped_folds
            else "n/a"
        )
        return (
            f"row-wise CV      F1 {self.row_wise_f1:.3f}   "
            f"({self.overlap_share:.0%} of test items also appear in train)\n"
            f"grouped CV       F1 {self.grouped_f1:.3f}   "
            f"(fold range {spread})\n"
            f"protocol gap     {self.gap:+.3f}   "
            f"-- same data, same model, different split"
        )


def grouping_gap(
    items: Sequence[str],
    labels: Sequence[int],
    groups: Sequence[Hashable],
    fit_predict: Callable[[Sequence[str], Sequence[int], Sequence[str]], list[int]],
    k: int = 5,
    seed: int = 0,
) -> GroupingGap:
    """Score the same model under both protocols. The difference is the leak.

    `fit_predict(train_x, train_y, test_x) -> predictions`. Supply whatever
    classifier you like; the comparison is about the split, not the model.
    """
    if not (len(items) == len(labels) == len(groups)):
        raise ValueError("items, labels and groups must be the same length")

    def run(folds):
        scores, overlaps = [], []
        for tr, te in folds:
            if not tr or not te:
                continue
            pred = fit_predict(
                [items[i] for i in tr], [labels[i] for i in tr], [items[i] for i in te]
            )
            scores.append(_f1(pred, [labels[i] for i in te]))
            tr_items, te_items = {items[i] for i in tr}, {items[i] for i in te}
            overlaps.append(len(tr_items & te_items) / len(te_items) if te_items else 0.0)
        return scores, overlaps

    row_s, row_o = run(row_folds(len(items), k, seed))
    grp_s, _ = run(group_folds(groups, k, seed))

    return GroupingGap(
        row_wise_f1=sum(row_s) / len(row_s) if row_s else 0.0,
        grouped_f1=sum(grp_s) / len(grp_s) if grp_s else 0.0,
        grouped_folds=grp_s,
        overlap_share=sum(row_o) / len(row_o) if row_o else 0.0,
    )


# --------------------------------------------------------------------------
# A reference classifier, so the comparison needs no dependencies
# --------------------------------------------------------------------------


def naive_bayes_fit_predict(
    train_x: Sequence[str], train_y: Sequence[int], test_x: Sequence[str]
) -> list[int]:
    """Multinomial naive Bayes with add-one smoothing.

    Deliberately simple and weak. If a model this crude scores perfectly under
    row-wise splitting, the benchmark is doing the work, not the model.
    """
    cnt = {0: Counter(), 1: Counter()}
    tot = {0: 0, 1: 0}
    prior = {0: 0, 1: 0}
    for s, y in zip(train_x, train_y):
        prior[y] += 1
        for w in re.findall(r"[a-z']{2,}", s.lower()):
            cnt[y][w] += 1
            tot[y] += 1
    n = sum(prior.values()) or 1
    lp = {c: math.log((prior[c] + 1) / (n + 2)) for c in (0, 1)}
    vocab = (set(cnt[0]) | set(cnt[1])) or {"<unk>"}
    v = len(vocab)

    out = []
    for s in test_x:
        sc = dict(lp)
        for w in re.findall(r"[a-z']{2,}", s.lower()):
            for c in (0, 1):
                sc[c] += math.log((cnt[c][w] + 1) / (tot[c] + v))
        out.append(1 if sc[1] > sc[0] else 0)
    return out
